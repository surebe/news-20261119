# Normalise common typographic characters to the ASCII set above.
_NORMALISE = {
    "‘": "'", "’": "'", "‚": ",", "“": '"', "”": '"',
    "–": "-", "—": "-", "−": "-", "…": "...",
    "•": "*", "·": ".", "°": "o", " ": " ",
    "«": '"', "»": '"', "‹": "'", "›": "'",
}


def normalise(text):
    out = []
    for ch in text:
        if ch in _NORMALISE:
            out.append(_NORMALISE[ch])
        elif ch in GLYPHS:
            out.append(ch)
        elif 32 <= ord(ch) < 127:
            out.append(ch)
        else:
            out.append("?")
    return "".join(out)


def text_width(text, scale=1, tracking=1):
    """Pixel width of a string at an integer scale."""
    text = normalise(text)
    if not text:
        return 0
    return len(text) * 6 * scale - tracking * scale


def draw_text(cv, x, y, text, scale=1, color=(0, 0, 0), bold=False,
              tracking=1):
    """Draw text with its top-left at (x, y). Returns the x end."""
    text = normalise(text)
    cx = x
    off = max(1, scale // 2) if bold else 0
    for ch in text:
        glyph = GLYPHS.get(ch, GLYPHS["?"])
        for row_i, row in enumerate(glyph):
            for col_i, cell in enumerate(row):
                if cell == "#":
                    px = cx + col_i * scale
                    py = y + row_i * scale
                    cv.rect(px, py, scale, scale, color)
                    if off:
                        cv.rect(px + off, py, scale, scale, color)
        cx += (5 + tracking) * scale
    return cx


def wrap(text, scale, max_width, tracking=1):
    """Greedy word wrap. Returns a list of lines that fit max_width."""
    words = normalise(text).split()
    lines = []
    cur = ""
    for word in words:
        trial = word if not cur else cur + " " + word
        if text_width(trial, scale, tracking) <= max_width or not cur:
            cur = trial
        else:
            lines.append(cur)
            cur = word
    if cur:
        lines.append(cur)
    return lines
