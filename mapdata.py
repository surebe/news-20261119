LAT_TOP = 84
LAT_BOT = -60


def project(lon, lat, x, y, w, h):
    """Equirectangular projection into the rect (x, y, w, h)."""
    px = x + (lon + 180) / 360.0 * w
    py = y + (LAT_TOP - lat) / (LAT_TOP - LAT_BOT) * h
    return int(px), int(py)


def draw_map(cv, x, y, w, h, ocean, land, grid=(255, 255, 255)):
    cv.rect(x, y, w, h, ocean)
    # faint graticule every 30 degrees
    for lon in range(-150, 180, 30):
        gx, _ = project(lon, 0, x, y, w, h)
        for yy in range(y, y + h, 6):
            cv.rect(gx, yy, 1, 3, grid)
    for lat in range(-60, 90, 30):
        _, gy = project(0, lat, x, y, w, h)
        for xx in range(x, x + w, 6):
            cv.rect(xx, gy, 3, 1, grid)
    for polygon in LAND:
        pts = [project(lon, lat, x, y, w, h) for lon, lat in polygon]
        cv.poly(pts, land)
